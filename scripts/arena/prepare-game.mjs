// Turns a full Limit Arena HTML build into two separate outputs:
//   1. public/games/limit-arena.html: minified, with no questions or answers.
//   2. A private questions JSON file, for import-questions.mjs. It must stay outside this repo.
//
// node scripts/arena/prepare-game.mjs <full-game.html> --questions <outside-repo.json>
// Needs esbuild: run `npm install --no-save esbuild` first, or point
// O2I_ESBUILD_MODULE at an installed copy. --keep-test-hooks and --out are only
// for local browser tests.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = fileURLToPath(new URL('../../', import.meta.url));
const args = process.argv.slice(2);
const flag = name => { const i = args.indexOf(name); return i < 0 ? undefined : args[i + 1]; };
const input = args[0];
const questionsPath = flag('--questions');
const keepHooks = args.includes('--keep-test-hooks');
const outPath = resolve(flag('--out') ?? resolve(root, 'public/games/limit-arena.html'));
assert.ok(input && questionsPath, 'Usage: prepare-game.mjs <full-game.html> --questions <outside-repo.json>');
const fromRoot = relative(root, resolve(questionsPath));
assert.ok(fromRoot.startsWith('..'), 'The questions file must stay outside this repo.');

const require = createRequire(import.meta.url);
const esbuild = require(process.env.O2I_ESBUILD_MODULE ?? 'esbuild');

let html = readFileSync(input, 'utf8');
const swap = (from, to) => {
  const count = html.split(from).length - 1;
  assert.equal(count, 1, `Expected exactly one match, found ${count}: ${from.slice(0, 70)}`);
  html = html.replace(from, () => to);
};
const swapBetween = (start, end, to) => {
  const a = html.indexOf(start);
  const b = html.indexOf(end, a);
  assert.ok(a >= 0 && b > a, `Could not find section: ${start.slice(0, 70)}`);
  html = html.slice(0, a) + to + html.slice(b);
};

// ---- take the question bank out
const bankLine = html.split('\n').find(line => line.startsWith('const QBANK = '));
assert.ok(bankLine, 'QBANK not found.');
const bank = JSON.parse(bankLine.slice(bankLine.indexOf('[')).trimEnd().replace(/;$/, ''));
html = html.replace(bankLine + '\n', () => '');
html = html.replace(/^\/\/ generated by build\/render_offline\.js.*\n/m, '');

const questions = bank.map(q => {
  assert.equal(q.opts.length, 4, `${q.id} needs four options.`);
  return {
    id: q.id, unit: q.unit, tier: q.tier, topic: q.topic, stem: q.stem,
    options: q.opts, explanation: q.exp, graph: q.graph ?? null, table_html: q.table ?? null,
  };
});

// ---- talk to the host page instead of reading QBANK
swap('<script>\n', `<script>
if (window.parent === window) location.replace('/arena');
const ARENA = {
  counts: {}, seq: 0, pending: new Map(),
  call(action, payload) {
    return new Promise((resolve, reject) => {
      const id = ++this.seq;
      const timer = setTimeout(() => { this.pending.delete(id); reject(new Error('timeout')); }, 8000);
      this.pending.set(id, { resolve, reject, timer });
      window.parent.postMessage({ source: 'limit-arena', id, action, payload }, location.origin);
    });
  },
  receive(e) {
    if (e.source !== window.parent || e.origin !== location.origin) return;
    const m = e.data;
    if (!m || m.source !== 'limit-arena-host') return;
    const p = this.pending.get(m.id);
    if (!p) return;
    this.pending.delete(m.id); clearTimeout(p.timer);
    if (m.ok) p.resolve(m.data); else p.reject(new Error('request failed'));
  },
};
window.addEventListener('message', e => ARENA.receive(e));
`);
swap('const unitQs = u => QBANK.filter(q => q.unit === u).length;', 'const unitQs = u => ARENA.counts[u] || 0;');
swap('const n = QBANK.filter(q => su.units.includes(q.unit)).length;', 'const n = su.units.reduce((sum, u) => sum + unitQs(u), 0);');
swap('qSeen: new Set(),', 'runId: crypto.randomUUID(),');
swap('R.lvQ = pickQuestion();', 'pickQuestion();');

swapBetween('  const inU = q => R.units.includes(q.unit)', 'function answered(ok) {', `  // Ask early: the level-up animation covers the round trip.
  const request = R.lvRequest = {};
  R.lvQ = null;
  ARENA.call('next', { runId: R.runId, units: R.units, currentUnit: R.curUnit, tier, preferCurrent: Math.random() <= 0.7 })
    .then(q => q || { status: 'error' }, () => ({ status: 'error' }))
    .then(q => { if (R.lvRequest === request) R.lvQ = q; });
}
`);
swap(`else if (STATE === 'lvup' && T - R.lvT >= R.lvDur) { STATE = 'quiz'; UI.quiz(R.lvQ); }`,
  `else if (STATE === 'lvup' && T - R.lvT >= R.lvDur && R.lvQ) { STATE = 'quiz'; if (R.lvQ.status === 'ok') UI.quiz(R.lvQ); else UI.quizUnavailable(R.lvQ.status); }`);

// The server shuffles the options, so the display order is already final.
swapBetween('    const order = [0, 1, 2, 3]; for (let i = 3;', `    const stars = '★'.repeat(q.tier)`, '');
swap("${order.map((oi, k) => `<button type=\"button\" class=\"qo\" data-k=\"${k}\"><kbd>${'ABCD'[k]}</kbd><span>${q.opts[oi]}</span></button>`).join('')}",
  "${q.opts.map((opt, k) => `<button type=\"button\" class=\"qo\" data-k=\"${k}\"><kbd>${'ABCD'[k]}</kbd><span>${opt}</span></button>`).join('')}");

swapBetween('  answer(k) {\n', '  cardsFor(opts, title, basic) {', `  answer(k) {
    if (this.mode !== 'quiz' || performance.now() < this.lock) return;
    const q = this.q;
    this.mode = 'quizwait';
    this.el.querySelectorAll('.qo').forEach(b => { b.disabled = true; });
    ARENA.call('answer', { issueId: q.issue_id, index: k })
      .then(r => (r && r.status === 'ok' ? r : null), () => null)
      .then(r => { if (this.q === q && this.mode === 'quizwait') this.reveal(k, r); });
  },
  reveal(k, r) {
    this.mode = 'quizfb';
    const fb = $('qfb'); fb.hidden = false;
    this.el.querySelector('.qz').classList.add('answered');
    if (!r) {
      fb.className = 'qfb no';
      fb.innerHTML = '<b>Could not check your answer</b><p>The question server did not respond. Take a basic reward and keep playing.</p>';
      this.cardsFor(basicOptions(), 'Pick a basic reward', true);
      return;
    }
    const ok = r.correct, opts = answered(ok);
    ok ? Snd.correct() : Snd.wrong();
    this.el.querySelectorAll('.qo').forEach((b, i) => { if (i === r.correct_index) b.classList.add('right'); else if (i === k) b.classList.add('wrong'); });
    const right = 'ABCD'[r.correct_index];
    fb.className = 'qfb ' + (ok ? 'ok' : 'no');
    fb.innerHTML = \`<b>\${ok ? '✓ Correct!' + (R.streak >= 3 ? \` Streak ×\${R.streak} · pick 1 of 4\` : '') + (R.streak && R.streak % 5 === 0 ? ' · +1 Reroll!' : '') : \`✗ The answer is \${right}\`}</b><p>\${r.explanation}</p>\`;
    this.cardsFor(opts, ok ? 'Pick an upgrade' : 'Not quite: pick a basic reward', !ok);
  },
  quizUnavailable(status) {
    this.q = null;
    const reason = status === 'rate_limited' ? "You've reached the question limit for now." : status === 'empty' ? 'No questions are available for these units.' : 'The question server did not respond.';
    this.show(\`<div class="panel qz pix answered"><div class="qhd"><b>LEVEL UP!</b></div><div class="qfb no" id="qfb"><b>\${reason}</b><p>Take a basic reward and keep playing.</p></div><div class="cards" id="cards" hidden></div><div class="qfoot" id="qfoot"></div></div>\`, 'quiz');
    this.mode = 'quizfb';
    this.cardsFor(basicOptions(), 'Pick a basic reward', true);
  },
`);

swap('  UI.init();\n', `  UI.init();
  ARENA.call('catalog').then(r => { ARENA.counts = (r && r.counts) || {}; }, () => {});
`);

// ---- test hooks can read game state, so they never ship
if (keepHooks) swap("q: UI.mode === 'quiz' && UI.q ? { id: UI.q.id, correctKey: 'ABCD'[UI.order.indexOf(0)] } : null,", "q: UI.mode === 'quiz' && UI.q ? { issue: UI.q.issue_id, opts: UI.q.opts } : null,");
else swapBetween('// ------------------------------------------------------------------ test hooks', '// ------------------------------------------------------------------ boot', '');

// ---- minify
const script = /<script>\n([\s\S]*?)<\/script>/.exec(html);
assert.ok(script, 'Game script not found.');
const js = await esbuild.transform(script[1], {
  loader: 'js', format: 'iife', target: 'es2020', legalComments: 'none',
  minify: !keepHooks,
  banner: '/* Includes ZzFX, MIT License, Copyright (c) 2019 Frank Force, https://github.com/KilledByAPixel/ZzFX */',
});
html = html.replace(script[0], () => `<script>${js.code}</script>`);
const styles = [...html.matchAll(/<style>([\s\S]*?)<\/style>/g)];
for (const style of styles) {
  const css = await esbuild.transform(style[1], { loader: 'css', minify: true, legalComments: 'none' });
  html = html.replace(style[0], () => `<style>${css.code}</style>`);
}
html = html.replace(/<meta name="claude:viewport-fit-sides"[^>]*>\n?/, '');

// ---- refuse to write anything that still holds a question or answer
for (const q of questions) {
  // Short options like "Yes" also appear in ordinary interface text.
  for (const secret of [q.stem, q.explanation, ...q.options].filter(text => text.length >= 40)) {
    assert.ok(!html.includes(secret), `Question ${q.id} leaked into the public game.`);
  }
}
for (const banned of ['QBANK', 'correctKey'].concat(keepHooks ? [] : ['__dbg', 'render_game_to_text'])) {
  assert.ok(!html.includes(banned), `Public game still contains ${banned}.`);
}

mkdirSync(dirname(outPath), { recursive: true });
mkdirSync(dirname(resolve(questionsPath)), { recursive: true });
writeFileSync(outPath, html);
writeFileSync(questionsPath, JSON.stringify(questions));
console.log(`Public game: ${outPath} (${(html.length / 1024).toFixed(0)} KB)`);
console.log(`Private questions: ${questionsPath} (${questions.length})`);
